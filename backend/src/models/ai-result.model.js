/**
 * models/ai-result.model.js — NETRA-DR AI Result Model & Repository Abstraction
 *
 * Implements the AI result persistence data model and repository abstraction (Module 7).
 * Associates server-validated AI inference outputs with specific screening cases.
 *
 * Designed database-agnostic so that persistent storage (e.g. MongoDB/Mongoose)
 * can replace the in-memory store in a later module without changing controllers.
 *
 * Result Lifecycle States:
 *   - completed:   Inference completed successfully and result persisted
 *   - failed:      Inference failed upstream with safe error record
 *   - processing:  Inference is actively in-flight
 *
 * Result Ownership & Schema:
 *   - resultId:            Server-generated unique result identifier ('res_<uuid>')
 *   - caseId:              Unique identifier of associated screening case ('case_<uuid>')
 *   - inferenceRequestId:  Unique upstream trace ID generated by Module 6 ('inf_<uuid>')
 *   - status:              'completed' | 'failed' | 'processing'
 *   - inference:           Genuine structured AI output from Flask (never client-supplied)
 *   - createdAt:           ISO 8601 UTC timestamp
 *   - updatedAt:           ISO 8601 UTC timestamp
 */

'use strict';

const crypto = require('crypto');

const RESULT_STATUS = Object.freeze({
  COMPLETED:  'completed',
  FAILED:     'failed',
  PROCESSING: 'processing',
});

const VALID_RESULT_STATUSES = Object.freeze(Object.values(RESULT_STATUS));

// In-memory data store for AI inference results
const resultsById = new Map();
const resultsByCaseId = new Map();             // caseId -> Array<record> (chronological order)
const resultsByInferenceRequestId = new Map(); // inferenceRequestId -> record (idempotency index)

const AIResultModel = {
  RESULT_STATUS,
  VALID_RESULT_STATUSES,

  /**
   * Return a safe representation of an AI result object.
   * Strips any internal storage paths, stack traces, or credentials.
   *
   * @param {object} record
   * @returns {object|null}
   */
  toSafeResult(record) {
    if (!record) return null;

    const safe = {
      resultId:           record.resultId || record.id,
      caseId:             record.caseId,
      inferenceRequestId: record.inferenceRequestId,
      status:             record.status,
      createdAt:          record.createdAt,
      updatedAt:          record.updatedAt,
    };

    if (record.inference && typeof record.inference === 'object') {
      safe.inference = JSON.parse(JSON.stringify(record.inference));
    }

    if (record.error && typeof record.error === 'object') {
      safe.error = {
        code:    record.error.code || 'AI_SERVICE_ERROR',
        message: record.error.message || 'AI inference error occurred',
      };
    }

    return safe;
  },

  /**
   * Create and persist a new AI result.
   *
   * @param {object} data
   * @param {string} data.caseId             - Required case reference
   * @param {string} data.inferenceRequestId - Required inference trace ID
   * @param {object} [data.inference]        - Structured AI output
   * @param {string} [data.status]           - Result status (defaults to 'completed')
   * @param {object} [data.error]            - Error details if failed
   * @param {string} [data.resultId]         - Optional server-provided resultId
   * @returns {Promise<object>} Created safe result record
   */
  async create({ caseId, inferenceRequestId, inference, status = RESULT_STATUS.COMPLETED, error = null, resultId = null }) {
    if (!caseId || typeof caseId !== 'string' || caseId.trim().length === 0) {
      throw new Error('caseId is required to persist an AI result');
    }
    if (!inferenceRequestId || typeof inferenceRequestId !== 'string' || inferenceRequestId.trim().length === 0) {
      throw new Error('inferenceRequestId is required to persist an AI result');
    }
    if (!VALID_RESULT_STATUSES.includes(status)) {
      throw new Error(`Invalid AI result status: '${status}'. Valid statuses: ${VALID_RESULT_STATUSES.join(', ')}`);
    }

    const now = new Date().toISOString();
    const id = resultId && typeof resultId === 'string' && resultId.startsWith('res_')
      ? resultId.trim()
      : `res_${crypto.randomUUID()}`;

    const normalizedCaseId = caseId.trim();
    const normalizedInfId  = inferenceRequestId.trim();

    const record = {
      id,
      resultId:           id,
      caseId:             normalizedCaseId,
      inferenceRequestId: normalizedInfId,
      status,
      inference:          inference && typeof inference === 'object' ? JSON.parse(JSON.stringify(inference)) : null,
      error:              error && typeof error === 'object' ? { code: error.code, message: error.message } : null,
      createdAt:          now,
      updatedAt:          now,
    };

    // Store in primary index
    resultsById.set(id, record);

    // Store in case index
    const caseRecords = resultsByCaseId.get(normalizedCaseId) || [];
    caseRecords.push(record);
    resultsByCaseId.set(normalizedCaseId, caseRecords);

    // Store in inferenceRequestId index for idempotency
    resultsByInferenceRequestId.set(normalizedInfId, record);

    return AIResultModel.toSafeResult(record);
  },

  /**
   * Find an AI result by its unique resultId.
   *
   * @param {string} resultId
   * @returns {Promise<object|null>}
   */
  async findById(resultId) {
    if (!resultId || typeof resultId !== 'string') return null;
    const record = resultsById.get(resultId.trim());
    return record ? AIResultModel.toSafeResult(record) : null;
  },

  /**
   * Find an AI result by its inferenceRequestId (idempotency key).
   *
   * @param {string} inferenceRequestId
   * @returns {Promise<object|null>}
   */
  async findByInferenceRequestId(inferenceRequestId) {
    if (!inferenceRequestId || typeof inferenceRequestId !== 'string') return null;
    const record = resultsByInferenceRequestId.get(inferenceRequestId.trim());
    return record ? AIResultModel.toSafeResult(record) : null;
  },

  /**
   * Find the latest AI result associated with a case.
   *
   * @param {string} caseId
   * @returns {Promise<object|null>}
   */
  async findByCaseId(caseId) {
    if (!caseId || typeof caseId !== 'string') return null;
    const caseRecords = resultsByCaseId.get(caseId.trim());
    if (!caseRecords || caseRecords.length === 0) return null;

    // Return the latest result (last appended)
    const latest = caseRecords[caseRecords.length - 1];
    return latest ? AIResultModel.toSafeResult(latest) : null;
  },

  /**
   * Find all AI results associated with a case, sorted newest first.
   *
   * @param {string} caseId
   * @returns {Promise<Array<object>>}
   */
  async findAllByCaseId(caseId) {
    if (!caseId || typeof caseId !== 'string') return [];
    const caseRecords = resultsByCaseId.get(caseId.trim());
    if (!caseRecords || caseRecords.length === 0) return [];

    return [...caseRecords]
      .sort((a, b) => new Date(b.createdAt) - new Date(a.createdAt))
      .map(r => AIResultModel.toSafeResult(r));
  },

  /**
   * Find all AI results with optional filter.
   *
   * @param {object} [filter={}]
   * @returns {Promise<Array<object>>}
   */
  async findAll(filter = {}) {
    let records = Array.from(resultsById.values());

    if (filter.caseId) {
      records = records.filter(r => r.caseId === filter.caseId);
    }
    if (filter.status) {
      records = records.filter(r => r.status === filter.status);
    }

    records.sort((a, b) => new Date(b.createdAt) - new Date(a.createdAt));
    return records.map(r => AIResultModel.toSafeResult(r));
  },

  /**
   * Delete an AI result by its unique resultId.
   *
   * @param {string} resultId
   * @returns {Promise<boolean>}
   */
  async delete(resultId) {
    if (!resultId || typeof resultId !== 'string') return false;
    const record = resultsById.get(resultId.trim());
    if (!record) return false;

    resultsById.delete(record.id);
    resultsByInferenceRequestId.delete(record.inferenceRequestId);

    const caseRecords = resultsByCaseId.get(record.caseId);
    if (caseRecords) {
      const filtered = caseRecords.filter(r => r.id !== record.id);
      if (filtered.length > 0) {
        resultsByCaseId.set(record.caseId, filtered);
      } else {
        resultsByCaseId.delete(record.caseId);
      }
    }

    return true;
  },

  /**
   * Delete all AI results for a given case.
   *
   * @param {string} caseId
   * @returns {Promise<number>} Number of deleted results
   */
  async deleteByCaseId(caseId) {
    if (!caseId || typeof caseId !== 'string') return 0;
    const caseRecords = resultsByCaseId.get(caseId.trim());
    if (!caseRecords || caseRecords.length === 0) return 0;

    const count = caseRecords.length;
    for (const r of caseRecords) {
      resultsById.delete(r.id);
      resultsByInferenceRequestId.delete(r.inferenceRequestId);
    }
    resultsByCaseId.delete(caseId.trim());
    return count;
  },

  /**
   * Clear all stored AI results (for test suite isolation).
   */
  async clear() {
    resultsById.clear();
    resultsByCaseId.clear();
    resultsByInferenceRequestId.clear();
  },

  /**
   * Count total stored AI results.
   *
   * @returns {Promise<number>}
   */
  async count() {
    return resultsById.size;
  },
};

module.exports = AIResultModel;
